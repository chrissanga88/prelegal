// Copies the Mutual NDA Standard Terms from the repository's templates/
// directory into a TypeScript module, so the app bundles them at build time
// and never reads files outside frontend/ at runtime.
// Run with `npm run sync-templates` after editing templates/Mutual-NDA.md.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const source = new URL("../../templates/Mutual-NDA.md", import.meta.url);
const target = new URL("../lib/nda/standardTermsSource.generated.ts", import.meta.url);

const markdown = readFileSync(source, "utf-8");
writeFileSync(
  target,
  `// Generated by scripts/sync-standard-terms.mjs from templates/Mutual-NDA.md. Do not edit.\n` +
    `export const STANDARD_TERMS_MARKDOWN = ${JSON.stringify(markdown)};\n`,
);
console.log(`Wrote ${fileURLToPath(target)}`);
