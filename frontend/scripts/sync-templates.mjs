// Bundles the document specs (documents.json) and their Common Paper templates
// (templates/) from the repository root into a TypeScript module, so the app
// ships them at build time and never reads files outside frontend/ at runtime.
// Run with `npm run sync-templates` after editing documents.json or a template.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../../", import.meta.url);
const target = new URL("../lib/documents/catalog.generated.ts", import.meta.url);

const documents = JSON.parse(readFileSync(new URL("documents.json", root), "utf-8"));
const templates = Object.fromEntries(
  documents.map(({ template }) => [template, readFileSync(new URL(template, root), "utf-8")]),
);

writeFileSync(
  target,
  `// Generated by scripts/sync-templates.mjs from documents.json and templates/. Do not edit.\n` +
    `import type { DocumentSpec } from "./types";\n\n` +
    `export const DOCUMENTS: DocumentSpec[] = ${JSON.stringify(documents, null, 2)};\n\n` +
    `export const TEMPLATES: Record<string, string> = ${JSON.stringify(templates, null, 2)};\n`,
);
console.log(`Wrote ${fileURLToPath(target)}`);
